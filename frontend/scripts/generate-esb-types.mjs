import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import prettier from 'prettier';
import { parse } from 'yaml';

const frontendRoot = resolve(import.meta.dirname, '..');
const contractsRoot = resolve(frontendRoot, '../contracts');
const generatedRoot = resolve(frontendRoot, 'shared-ui/src/generated');

async function readContract(name) {
  const sourceBytes = await readFile(resolve(contractsRoot, name));
  return { document: parse(sourceBytes.toString('utf8')), sourceBytes };
}

async function emit(outputName, source, document, sourceBytes) {
  const outputPath = resolve(generatedRoot, outputName);
  const generated = astToString(await openapiTS(document));
  const digest = createHash('sha256').update(sourceBytes).digest('hex');
  const prettierConfig = (await prettier.resolveConfig(outputPath)) ?? {};
  const output = await prettier.format(
    `// Generated from contracts/${source}. Do not edit manually.\n// Contract SHA-256: ${digest}\n${generated}`,
    { ...prettierConfig, parser: 'typescript' },
  );
  await mkdir(generatedRoot, { recursive: true });
  await writeFile(outputPath, output, 'utf8');
}

// The AsyncAPI payloads are self-contained JSON Schemas that address their local
// definitions as `#/$defs/...`. Those pointers stop resolving once a payload is lifted
// into a shared components section, so each local definition is expanded in place.
function inlineLocalDefs(schema, defs) {
  if (Array.isArray(schema)) return schema.map((item) => inlineLocalDefs(item, defs));
  if (!schema || typeof schema !== 'object') return schema;
  if (typeof schema.$ref === 'string' && schema.$ref.startsWith('#/$defs/')) {
    const name = schema.$ref.slice('#/$defs/'.length);
    if (!(name in defs)) throw new Error(`Unresolved local definition ${schema.$ref}`);
    return inlineLocalDefs(defs[name], defs);
  }
  return Object.fromEntries(
    Object.entries(schema)
      .filter(([key]) => key !== '$defs')
      .map(([key, value]) => [key, inlineLocalDefs(value, defs)]),
  );
}

// The browser WebSocket frames are only described by the AsyncAPI document. Its message
// payloads are plain JSON Schema, so they are lifted into a schema-only OpenAPI document
// and generated by the same tool instead of being transcribed by hand.
function asyncApiSchemaDocument(asyncapi) {
  const schemas = asyncapi.components?.schemas ?? {};
  const required = [
    'RealtimeClientMessage',
    'RealtimeMessage',
    'RealtimeServerControlMessage',
  ];
  const missing = required.filter((name) => !(name in schemas));
  if (missing.length) throw new Error(`AsyncAPI is missing canonical schemas: ${missing.join(', ')}`);
  return {
    openapi: '3.1.0',
    info: { title: asyncapi.info.title, version: asyncapi.info.version },
    paths: {},
    // Preserve BookingStatus and any future shared schemas referenced by message payloads.
    components: { schemas },
  };
}

const esb = await readContract('esb-public-api.yaml');
await emit('esb-public-api.ts', 'esb-public-api.yaml', esb.document, esb.sourceBytes);
const identity = await readContract('providers/identity-service.yaml');
await emit(
  'identity-service.ts',
  'providers/identity-service.yaml',
  identity.document,
  identity.sourceBytes,
);
const realtimeOpenApi = await readContract('providers/realtime-status-service.yaml');
await emit(
  'realtime-service.ts',
  'providers/realtime-status-service.yaml',
  realtimeOpenApi.document,
  realtimeOpenApi.sourceBytes,
);
const realtimeAsyncApi = await readContract('providers/realtime-status.asyncapi.yaml');
await emit(
  'realtime-messages.ts',
  'providers/realtime-status.asyncapi.yaml',
  asyncApiSchemaDocument(realtimeAsyncApi.document),
  realtimeAsyncApi.sourceBytes,
);
